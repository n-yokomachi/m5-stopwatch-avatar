"""Generate the launcher icon for the voice chat app (200x200 RGB565 LVGL image).

Two white rounded-rectangle eyes on a dark disc, the same proportions as the app's
idle screen (eye 78 x 118, corner radius 34, gap 150), placed above the centre.
Usage: uv run --with pillow python tools/make_icon.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "main" / "assets" / "images" / "icon_avatar.c"
SIZE = 200


def eyes_rgb565() -> list[int]:
    ss = 4  # supersample for smooth edges
    im = Image.new("RGB", (SIZE * ss, SIZE * ss), (0, 0, 0))
    d = ImageDraw.Draw(im)
    d.ellipse((0, 0, SIZE * ss - 1, SIZE * ss - 1), fill=(24, 24, 28))
    k = 0.40 * ss
    c, ey = SIZE * ss / 2, SIZE * ss * 0.40
    w, h, r, gap = 78 * k, 118 * k, 34 * k, 150 * k
    for side in (-1, 1):
        ex = c + side * gap / 2
        d.rounded_rectangle((ex - w / 2, ey - h / 2, ex + w / 2, ey + h / 2), radius=r, fill=(255, 255, 255))
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    return [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in im.get_flattened_data()]


def main() -> None:
    data = []
    for v in eyes_rgb565():  # LV_COLOR_FORMAT_RGB565 is little-endian
        data += [v & 0xFF, v >> 8]
    body = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 19]) for i in range(0, len(data), 19))
    OUT.write_text(f"""// Generated by tools/make_icon.py. Do not edit.
#include "lvgl.h"

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t icon_avatar_map[] = {{
{body},
}};

const lv_image_dsc_t icon_avatar = {{
    .header.cf    = LV_COLOR_FORMAT_RGB565,
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.w     = {SIZE},
    .header.h     = {SIZE},
    .data_size    = {SIZE * SIZE * 2},
    .data         = icon_avatar_map,
}};
""")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
