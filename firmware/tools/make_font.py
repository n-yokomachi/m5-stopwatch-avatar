"""Convert Noto Sans JP into a VLW font (smooth font for M5GFX) as a C header.

Glyphs: ASCII, JIS X 0208 non-kanji rows (symbols, kana, alphanumerics) and
JIS level 1 kanji, plus a few extra characters. The full kanji set does not fit
in the app partition next to the code.
Usage: uv run --with freetype-py python tools/make_font.py [pixel_size]
"""

import struct
import sys
from pathlib import Path

import freetype

HERE = Path(__file__).resolve().parent
FONT = HERE.parent / "fonts" / "NotoSansJP-Medium.otf"
OUT = HERE.parent / "src" / "font_noto.h"
EXTRA = "…〜～・「」『』（）！？％＆＋－＝＠＃｜／"
# JIS level 2 kanji that often come up in replies (food words etc.);
# anything else outside the font is drawn with M5GFX's built-in Japanese font.
EXTRA += "曖炒姜椒茹彙閾璧捏罠俯瞰恣顆綺喩乖丼茗緻哺扁褄蕾淹揉謳鬱瞞國腑泄嘔躁箋敲躓竄剪"


def charset() -> list[int]:
    cps = set(range(0x20, 0x7F))
    # JIS X 0208 rows 1-8 (symbols, digits, latin, kana, greek, cyrillic, box)
    # and rows 16-47 (level 1 kanji), via EUC-JP
    for row in list(range(1, 9)) + list(range(16, 48)):
        for cell in range(1, 95):
            try:
                ch = bytes([0xA0 + row, 0xA0 + cell]).decode("euc_jp")
            except UnicodeDecodeError:
                continue
            cps.add(ord(ch))
    cps.update(ord(c) for c in EXTRA)
    return sorted(c for c in cps if c <= 0xFFFF)


def main() -> None:
    size = int(sys.argv[1]) if len(sys.argv) > 1 else 24
    face = freetype.Face(str(FONT))
    face.set_pixel_sizes(0, size)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)

    headers, bitmaps = [], []
    for cp in charset():
        if face.get_char_index(cp) == 0:
            continue
        face.load_char(cp, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        rows = [bytes(bm.buffer[r * bm.pitch : r * bm.pitch + w]) for r in range(h)]
        headers.append(struct.pack(">7i", cp, h, w, g.advance.x >> 6, g.bitmap_top, g.bitmap_left, 0))
        bitmaps.append(b"".join(rows))

    data = struct.pack(">6i", len(headers), 11, size, 0, ascent, descent) + b"".join(headers) + b"".join(bitmaps)
    lines = [
        "// Generated by tools/make_font.py from Noto Sans JP Medium (SIL Open Font License 1.1).",
        "#pragma once",
        "#include <stdint.h>",
        f"// {len(headers)} glyphs, {size}px",
        "static const uint8_t FONT_NOTO[] = {",
    ]
    for i in range(0, len(data), 32):
        lines.append(",".join(str(b) for b in data[i : i + 32]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(headers)} glyphs, {len(data) / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
